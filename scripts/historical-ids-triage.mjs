#!/usr/bin/env node
// Evidence-only triage of the 143 historical acceptance IDs. It NEVER marks an ID accepted:
// it records facts (do the referenced files exist, do the referenced automated tests pass NOW) and a conservative class.
// Usage: node scripts/historical-ids-triage.mjs [--run]   (--run executes referenced tests; otherwise reuses the last result file)
import {readFileSync,writeFileSync,existsSync} from "node:fs";
import {spawnSync} from "node:child_process";

const SRC="docs/release/ROAD_TO_COMPLETE_HISTORICAL_IDS.json", OUT_JSON="docs/release/HISTORICAL_IDS_TRIAGE.json", OUT_MD="docs/release/HISTORICAL_IDS_TRIAGE.md";
const src=JSON.parse(readFileSync(SRC,"utf8"));
const isTest=f=>/\.test\.(ts|tsx|mjs|cjs)$/.test(f);
const isBrowserSpec=f=>/\.spec\.(mjs|ts)$/.test(f);
const tests=[...new Set(src.records.flatMap(r=>r.files.filter(f=>existsSync(f)&&isTest(f))))].sort();

let results={};
if(process.argv.includes("--run")){
  const vitest=tests.filter(f=>f.startsWith("client/")), node=tests.filter(f=>!f.startsWith("client/"));
  for(const f of node){const r=spawnSync("node",["--test",f],{encoding:"utf8",timeout:300000});results[f]=r.status===0?"pass":"fail";}
  for(const f of vitest){const r=spawnSync("pnpm",["exec","vitest","run",f],{encoding:"utf8",timeout:300000});
    results[f]=r.status===0?"pass":"fail";}
  writeFileSync(".historical-ids-test-results.json",JSON.stringify(results,null,1));
}else if(existsSync(".historical-ids-test-results.json")) results=JSON.parse(readFileSync(".historical-ids-test-results.json","utf8"));

const classify=r=>{
  const t=r.files.filter(f=>existsSync(f)&&isTest(f)), spec=r.files.filter(f=>existsSync(f)&&isBrowserSpec(f));
  if(!r.files.length) return "open-blocker-register-entry";
  if(r.missingReferencedPaths.length) return "references-missing-files";
  if(t.length&&t.every(f=>results[f]==="pass")) return "automated-tests-pass-criterion-review-pending";
  if(t.length) return results[t[0]]===undefined?"tests-not-run":"referenced-test-failing";
  if(spec.length) return "browser-spec-only";
  return "no-referenced-test";
};
const records=src.records.map(r=>({id:r.id,family:r.family,requirement:r.requirement,historicalStatus:r.historicalStatus,
  referencedTests:r.files.filter(f=>existsSync(f)&&isTest(f)).map(f=>({file:f,result:results[f]??"not-run"})),
  triageClass:classify(r),accepted:false,
  note:"Not accepted. 'pass' only means the referenced automated tests currently pass; the original criterion still needs line-by-line review and, where it is a device/owner criterion, real-world acceptance."}));
writeFileSync(OUT_JSON,JSON.stringify({generatedFrom:SRC,count:records.length,records},null,1)+"\n");
const by={};for(const r of records)(by[r.triageClass]??=[]).push(r);
const md=["# Historical acceptance ID triage","","Generated by `scripts/historical-ids-triage.mjs`. **No ID is accepted by this triage.** Source: `ROAD_TO_COMPLETE_HISTORICAL_IDS.json` (143 records).","",
 "| Class | Count | Meaning |","|---|---|---|"];
const meaning={"automated-tests-pass-criterion-review-pending":"Referenced test files exist and pass now. Criterion still needs review against the test content.",
 "no-referenced-test":"Only source files are referenced; no executed test is linked. Needs a criterion-to-test mapping or a new test.",
 "open-blocker-register-entry":"A blocker-register item with no file references; open by definition until its blocker is cleared.",
 "referenced-test-failing":"A referenced test currently fails: investigate.","tests-not-run":"Not executed in this run.","browser-spec-only":"Only a browser spec is linked; run in the device-engine CI.","references-missing-files":"Referenced file no longer exists."};
for(const [k,v] of Object.entries(by).sort())md.push(`| ${k} | ${v.length} | ${meaning[k]??""} |`);
md.push("","## By family and historical status","","| Family | implemented-unverified | implemented-and-tested | missing | blocked | unverified |","|---|---|---|---|---|---|");
for(const fam of ["acceptance","release","central"]){const rs=records.filter(r=>r.family===fam);const c=s=>rs.filter(r=>r.historicalStatus===s).length;
 md.push(`| ${fam} (${rs.length}) | ${c("implemented-unverified")} | ${c("implemented-and-tested")} | ${c("missing")} | ${c("blocked")} | ${c("unverified")} |`);}
md.push("","## Records","","| ID | Family | Historical | Class | Referenced tests |","|---|---|---|---|---|");
for(const r of records)md.push(`| ${r.id} | ${r.family} | ${r.historicalStatus} | ${r.triageClass} | ${r.referencedTests.map(t=>t.file.split("/").pop()+":"+t.result).join(", ")||"-"} |`);
writeFileSync(OUT_MD,md.join("\n")+"\n");
console.log(Object.fromEntries(Object.entries(by).map(([k,v])=>[k,v.length])));
