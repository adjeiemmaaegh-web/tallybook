#!/usr/bin/env node
// For IDs with no linked test: find existing test files that IMPORT the ID's source modules (static, by module basename).
// Facts only: "candidate covering tests" are leads for the criterion review, not proof of coverage.
import {readFileSync,writeFileSync,readdirSync,statSync,existsSync} from "node:fs";
import {join,basename} from "node:path";
const walk=(d,out=[])=>{for(const n of readdirSync(d)){if(["node_modules","dist",".git","artifacts"].includes(n))continue;const p=join(d,n);const s=statSync(p);
  if(s.isDirectory())walk(p,out);else if(/\.test\.(ts|tsx|mjs|cjs)$/.test(n))out.push(p);}return out;};
const tests=[...walk("client/src"),...walk("qa"),...walk("server")].map(p=>({p,text:readFileSync(p,"utf8")}));
const src=JSON.parse(readFileSync("docs/release/ROAD_TO_COMPLETE_HISTORICAL_IDS.json","utf8"));
const tri=JSON.parse(readFileSync("docs/release/HISTORICAL_IDS_TRIAGE.json","utf8"));
const mods=f=>{const b=basename(f).replace(/\.(ts|tsx|mjs|cjs)$/,"");return b;};
const generic=new Set(["App","index","main"]);
const out=[];
for(const r of tri.records.filter(r=>r.triageClass==="no-referenced-test")){
  const s=src.records.find(x=>x.id===r.id);
  const sources=s.files.filter(f=>existsSync(f)&&/\.(ts|tsx|mjs|cjs)$/.test(f)&&!/\.test\./.test(f)).map(mods).filter(m=>!generic.has(m));
  const hit=new Map();
  for(const m of sources){
    const re=new RegExp(`from\\s+["'][^"']*\\/${m}(\\.m?[jt]sx?)?["']|require\\(["'][^"']*\\/${m}["']\\)|import\\(["'][^"']*\\/${m}(\\.m?[jt]sx?)?["']\\)`);
    for(const t of tests)if(re.test(t.text)){(hit.get(t.p)??new Set()).add(m);hit.set(t.p,hit.get(t.p)??new Set());hit.get(t.p).add(m);}
  }
  out.push({id:r.id,family:r.family,historicalStatus:r.historicalStatus,requirement:r.requirement,sourceModules:sources,
    candidateTests:[...hit.entries()].map(([f,m])=>({file:f,imports:[...m]})).sort((a,b)=>b.imports.length-a.imports.length||a.file.localeCompare(b.file)).slice(0,6),
    verdict:hit.size?"candidate-tests-found-review-needed":(sources.length?"NO-TEST-IMPORTS-SOURCE":"no-source-modules")});
}
writeFileSync("docs/release/HISTORICAL_IDS_COVERAGE_LEADS.json",JSON.stringify({count:out.length,records:out},null,1)+"\n");
const c=k=>out.filter(o=>o.verdict===k).length;
const md=["# Historical IDs without a linked test: coverage leads","",
 "Generated by `scripts/historical-ids-coverage.mjs`. A lead means an existing test imports the same source module; it is **not** proof the criterion is covered. IDs marked **NO-TEST-IMPORTS-SOURCE** are genuine test gaps.","",
 `Candidate tests found: ${c("candidate-tests-found-review-needed")}; genuine gaps: ${c("NO-TEST-IMPORTS-SOURCE")}; no source module: ${c("no-source-modules")}.`,"",
 "| ID | Historical | Verdict | Requirement | Best candidate tests |","|---|---|---|---|---|"];
for(const o of out)md.push(`| ${o.id} | ${o.historicalStatus} | ${o.verdict} | ${o.requirement.replaceAll("|","/").slice(0,70)} | ${o.candidateTests.slice(0,3).map(t=>basename(t.file)).join(", ")||"-"} |`);
writeFileSync("docs/release/HISTORICAL_IDS_COVERAGE_LEADS.md",md.join("\n")+"\n");
console.log({candidates:c("candidate-tests-found-review-needed"),gaps:c("NO-TEST-IMPORTS-SOURCE"),noSource:c("no-source-modules")});
